  /* ---------- подсветка: куда легла правка ---------- */
  /* сравниваем абзацы «до» и «после» по тексту без номера: новые и изменённые
     помечаются, лист сам подкручивается к первому из них. */
  var hitTimer = null, quiet = true;
  function norm(s) { return String(s).replace(/^\d+\.\d+\.\s*/, "").replace(/\s+/g, " ").trim(); }
  function snapshot() {
    var m = {};
    [].forEach.call(paper.querySelectorAll("p, h3, h4, td"), function (e) { m[norm(e.innerText)] = 1; });
    return m;
  }
  function markChanges(prev) {
    var first = null;
    [].forEach.call(paper.querySelectorAll("p, h4, td"), function (e) {
      var t = norm(e.innerText);
      if (!t || prev[t]) return;
      e.classList.add("hit");
      if (!first) first = e;
    });
    if (!first) return;
    var pr = paper.getBoundingClientRect(), er = first.getBoundingClientRect();
    if (er.top < pr.top + 8 || er.bottom > pr.bottom - 8) {
      paper.scrollTop += (er.top - pr.top) - (paper.clientHeight - er.height) / 2;
    }
    clearTimeout(hitTimer);
    hitTimer = setTimeout(function () {
      [].forEach.call(paper.querySelectorAll(".hit"), function (e) { e.classList.add("hit-off"); });
    }, 1500);
  }

  var lastHtml = "";
  function render() {
    var s = read();
    syncVisibility(s);
    var html = mode === "dogovor" ? renderDogovor(s) : renderAkt(s);
    /* клик по варианту даёт и input, и change: без этой проверки второй рендер
       стирал бы подсветку, которую поставил первый */
    if (html === lastHtml) return;
    var prev = quiet ? null : snapshot();
    lastHtml = html;
    paper.innerHTML = html;
    if (prev) markChanges(prev);
    quiet = false;
  }

