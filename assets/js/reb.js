/* ПОБУБНИМ — конструктор согласия на съёмку ребёнка
   (instrumenty/soglasie-na-semku-rebenka.html).

   ПОЧЕМУ ЭТО НЕ ТО ЖЕ САМОЕ, ЧТО МОДЕЛЬНЫЙ РЕЛИЗ. Релиз закрывает один вопрос —
   изображение (ст. 152.1 ГК РФ). Школе, саду, студии и лагерю этого мало: имя,
   фамилия, возраст, класс и само изображение ребёнка — это персональные данные,
   и на их обработку нужно согласие по 152-ФЗ. Два разных основания в одной бумаге.

   ГЛАВНАЯ ТОНКОСТЬ, КОТОРУЮ ТЕРЯЮТ СКАЧАННЫЕ ОБРАЗЦЫ. С 01.03.2021 действует
   ст. 10.1 152-ФЗ: согласие на обработку персональных данных, РАЗРЕШЁННЫХ ДЛЯ
   РАСПРОСТРАНЕНИЯ (то есть на публикацию — сайт, соцсети, стенд, СМИ),
   оформляется ОТДЕЛЬНО от иных согласий (ч. 6 ст. 10.1). Пункт «разрешаю
   публиковать» внутри общего согласия этому требованию не отвечает. Поэтому
   конструктор собирает ДВА листа, а не один, и второй появляется только тогда,
   когда публикация действительно планируется.

   За несовершеннолетнего согласие даёт законный представитель: родители —
   законные представители своих детей и выступают в защиту их прав без
   особых полномочий (ст. 64 СК РФ).

   Всё считается и собирается в браузере, ничего никуда не уходит. */

(function () {
  var form = document.getElementById("cfg");
  var paper = document.getElementById("paper");
  if (!form || !paper) return;

  var tab1 = document.getElementById("tab-osn");
  var tab2 = document.getElementById("tab-rasp");
  var mode = "osn";

  function esc(s) {
    return String(s).replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }
  var BL = '<span class="blank">&nbsp;</span>';
  function bl(v) { return v ? esc(v) : BL; }
  function val(id) { return (document.getElementById(id) || {}).value || ""; }
  function radio(name) {
    var el = form.querySelector('input[name="' + name + '"]:checked');
    return el ? el.value : "";
  }
  function checked(id) {
    var el = document.getElementById(id);
    return !!(el && el.checked);
  }
  function ruDate(iso) {
    if (!iso) return null;
    var p = iso.split("-");
    return p.length === 3 ? p[2] + "." + p[1] + "." + p[0] : null;
  }

  /* Кем приходится представитель — влияет на формулировку основания. */
  var KIN = {
    mother: ["матерью", "свидетельством о рождении"],
    father: ["отцом", "свидетельством о рождении"],
    guardian: ["опекуном (попечителем)", "актом органа опеки и попечительства о назначении опекуна (попечителя)"],
    adoptive: ["усыновителем", "свидетельством об усыновлении"]
  };

  /* Куда планируется публикация. Каждый пункт — отдельный способ
     распространения, и по ст. 10.1 их надо перечислить, а не написать «везде». */
  var PLACES = [
    ["p-site", "на официальном сайте Оператора"],
    ["p-soc", "в официальных сообществах Оператора в социальных сетях и мессенджерах"],
    ["p-stend", "на информационных стендах, в фотоальбомах и печатных материалах Оператора"],
    ["p-smi", "в средствах массовой информации при освещении мероприятий Оператора"],
    ["p-ad", "в рекламных и презентационных материалах Оператора"]
  ];

  function places() {
    return PLACES.filter(function (p) { return checked(p[0]); }).map(function (p) { return p[1]; });
  }

  function operator() {
    var kind = radio("who");
    var name = val("f-org");
    if (kind === "person") return bl(name) + ", ИНН " + bl(val("f-inn"));
    return bl(name) + ", ИНН " + bl(val("f-inn")) + ", адрес: " + bl(val("f-addr"));
  }

  function termText() {
    var t = radio("term");
    if (t === "years") return "в течение " + bl(val("f-years")) + " лет с даты подписания";
    if (t === "study") return "в течение всего периода обучения (пребывания) ребёнка у Оператора и трёх лет после его окончания";
    return "бессрочно, до отзыва настоящего согласия";
  }

  /* ---------- лист 1: обработка персональных данных и изображение ---------- */
  function renderOsn() {
    var kin = KIN[radio("kin")] || KIN.mother;
    var pl = places();
    var media = radio("media");
    var mediaWord = media === "photo" ? "фотосъёмки" : media === "video" ? "видеосъёмки" : "фото- и видеосъёмки";
    var mediaRes = media === "photo" ? "фотографические изображения" : media === "video" ? "видеозаписи" : "фотографические изображения и видеозаписи";

    var h = ['<div class="bmark-row tl" aria-hidden="true"><span class="bmark">Б</span></div>'];
    h.push("<h2>СОГЛАСИЕ<br>на обработку персональных данных несовершеннолетнего<br>и на использование его изображения</h2>");
    h.push('<table class="doc-meta"><tr><td>г. ' + bl(val("f-city")) +
      '</td><td style="text-align:right">«___» ____________ 20___ г.</td></tr></table>');

    h.push("<p>Я, " + bl(val("f-parent")) + ", паспорт " + bl(val("f-passport")) +
      ", являясь " + kin[0] + " несовершеннолетнего " + bl(val("f-child")) +
      (val("f-birth") ? ", " + esc(ruDate(val("f-birth"))) + " года рождения" : ", «___» ____________ ______ года рождения") +
      " (далее — Ребёнок), что подтверждается " + kin[1] +
      ", действуя в его интересах как законный представитель (ст. 64 Семейного кодекса РФ), " +
      "даю согласие " + operator() + " (далее — Оператор) на следующее.</p>");

    h.push("<h3>1. Обработка персональных данных Ребёнка</h3>");
    /* Объём обрабатываемых данных обязан соответствовать цели (ч. 5 ст. 5
       152-ФЗ). Значит при съёмке только фото нельзя писать «и видеозаписи»:
       это лишняя категория, на которую согласия не спрашивали. */
    var imgWord = media === "photo" ? "фотографии с участием Ребёнка"
      : media === "video" ? "видеозаписи с участием Ребёнка"
      : "фотографии и видеозаписи с участием Ребёнка";
    h.push("<p>1.1. Даю согласие на обработку персональных данных Ребёнка: фамилия, имя" +
      (checked("d-patron") ? ", отчество" : "") + "; год и дата рождения; " +
      (checked("d-group") ? "класс (группа, объединение); " : "") +
      (checked("d-contact") ? "контактные данные законного представителя; " : "") +
      "изображение (" + imgWord + ").</p>");
    h.push("<p>1.2. Цель обработки: " + bl(val("f-goal")) + ". Обработка в иных целях настоящим согласием не охватывается (ст. 5 Федерального закона от 27.07.2006 № 152-ФЗ).</p>");
    h.push("<p>1.3. Перечень действий: сбор, запись, систематизация, накопление, хранение, уточнение, извлечение, использование, блокирование, удаление и уничтожение. Обработка ведётся как с использованием средств автоматизации, так и без них.</p>");
    h.push("<p>1.4. Согласие действует " + termText() + ".</p>");
    h.push("<p>1.5. Согласие может быть отозвано в любое время письменным заявлением на имя Оператора (ч. 2 ст. 9 Федерального закона № 152-ФЗ). После отзыва Оператор прекращает обработку и уничтожает персональные данные в установленный законом срок, если иное не предусмотрено законом.</p>");

    h.push("<h3>2. Съёмка и использование изображения</h3>");
    h.push("<p>2.1. Даю согласие на проведение " + mediaWord + " с участием Ребёнка " +
      (val("f-event") ? "в рамках: " + bl(val("f-event")) : "в рамках деятельности и мероприятий Оператора") +
      (val("f-place") ? ", место проведения: " + bl(val("f-place")) : "") +
      (val("f-date") ? ", дата: " + esc(ruDate(val("f-date"))) : "") + ".</p>");
    h.push("<p>2.2. Даю согласие на использование созданных " + mediaRes +
      " с участием Ребёнка в целях, указанных в пункте 1.2, включая обработку (кадрирование, цветокоррекция, монтаж) и использование целиком или фрагментами (ст. 152.1 Гражданского кодекса РФ).</p>");
    h.push("<p>2.3. Не допускается использование изображения Ребёнка способами, порочащими его честь, достоинство и деловую репутацию, а также в контексте, очевидно оскорбительном либо способном причинить вред его интересам.</p>");
    h.push("<p>2.4. Съёмка и использование изображения осуществляются безвозмездно. Вознаграждение Ребёнку и его законному представителю не выплачивается, если стороны не согласовали иное в письменной форме.</p>");

    if (pl.length) {
      h.push("<h3>3. Публикация</h3>");
      h.push("<p>3.1. Публикация персональных данных и изображения Ребёнка планируется " + esc(pl.join("; ")) + ".</p>");
      h.push("<p>3.2. Согласие на обработку персональных данных, разрешённых для распространения, оформляется ОТДЕЛЬНЫМ документом в силу части 6 статьи 10.1 Федерального закона № 152-ФЗ. Такое согласие дано приложением к настоящему документу и может быть отозвано независимо от него.</p>");
    } else {
      h.push("<h3>3. Публикация</h3>");
      h.push("<p>3.1. Публикация персональных данных и изображения Ребёнка настоящим согласием не предусмотрена. Материалы используются исключительно во внутренней деятельности Оператора в целях, указанных в пункте 1.2.</p>");
      h.push("<p>3.2. Если публикация потребуется, она оформляется отдельным согласием на обработку персональных данных, разрешённых для распространения (ч. 6 ст. 10.1 Федерального закона № 152-ФЗ).</p>");
    }

    h.push('<table class="req"><tr><td><b>Законный представитель</b>' + bl(val("f-parent")) +
      "<br>за несовершеннолетнего " + bl(val("f-child")) +
      '<div class="sig">Подпись: ' + BL + "</div></td>" +
      "<td><b>Оператор</b>" + bl(val("f-org")) +
      '<div class="sig">Подпись: ' + BL + "</div></td></tr></table>");
    h.push('<p class="doc-note">Типовой шаблон собран конструктором pobubnim.ru по ст. 152.1 ГК РФ и Федеральному закону № 152-ФЗ. Не является юридической консультацией.</p>');
    h.push('<div class="bmark-row br" aria-hidden="true"><span class="bmark">Б</span></div>');
    paper.innerHTML = h.join("");
  }

  /* ---------- лист 2: отдельное согласие на распространение (ст. 10.1) ---------- */
  function renderRasp() {
    var kin = KIN[radio("kin")] || KIN.mother;
    var pl = places();
    var h = ['<div class="bmark-row tl" aria-hidden="true"><span class="bmark">Б</span></div>'];
    h.push("<h2>СОГЛАСИЕ<br>на обработку персональных данных несовершеннолетнего,<br>разрешённых субъектом для распространения</h2>");
    h.push('<p class="doc-note" style="margin-top:0">Оформляется отдельно от иных согласий — часть 6 статьи 10.1 Федерального закона от 27.07.2006 № 152-ФЗ.</p>');
    h.push('<table class="doc-meta"><tr><td>г. ' + bl(val("f-city")) +
      '</td><td style="text-align:right">«___» ____________ 20___ г.</td></tr></table>');

    if (!pl.length) {
      h.push("<p><b>В форме не отмечено ни одного места публикации.</b> Этот лист нужен только тогда, когда персональные данные и изображение Ребёнка планируется публиковать: на сайте, в соцсетях, на стенде, в СМИ или в рекламных материалах. Отметьте нужное в разделе «Где публикуется» — и лист соберётся.</p>");
      h.push("<p>Если публикации не будет, второй документ не нужен: достаточно основного согласия.</p>");
      h.push('<div class="bmark-row br" aria-hidden="true"><span class="bmark">Б</span></div>');
      paper.innerHTML = h.join("");
      return;
    }

    h.push("<p>Я, " + bl(val("f-parent")) + ", паспорт " + bl(val("f-passport")) +
      ", являясь " + kin[0] + " несовершеннолетнего " + bl(val("f-child")) +
      (val("f-birth") ? ", " + esc(ruDate(val("f-birth"))) + " года рождения" : ", «___» ____________ ______ года рождения") +
      " (далее — Ребёнок), действуя в его интересах как законный представитель (ст. 64 Семейного кодекса РФ), " +
      "в соответствии со статьёй 10.1 Федерального закона № 152-ФЗ принимаю решение о предоставлении персональных данных Ребёнка для распространения и даю настоящее согласие оператору: " + operator() + ".</p>");

    h.push("<h3>1. Какие данные разрешены для распространения</h3>");
    h.push('<table class="items" data-cols="55,45"><tr><th>Категория данных</th><th>Разрешено распространять</th></tr>');
    h.push("<tr><td>Фамилия, имя" + (checked("d-patron") ? ", отчество" : "") + " Ребёнка</td><td>да</td></tr>");
    h.push("<tr><td>Изображение Ребёнка (фото, видео)</td><td>да</td></tr>");
    if (checked("d-group")) h.push("<tr><td>Класс, группа, объединение</td><td>да</td></tr>");
    if (checked("d-age")) h.push("<tr><td>Возраст (число полных лет)</td><td>да</td></tr>");
    h.push("<tr><td>Дата рождения, адрес, контактные данные</td><td>нет</td></tr>");
    h.push("<tr><td>Сведения о здоровье, иные специальные категории</td><td>нет</td></tr>");
    h.push("</table>");
    h.push("<p>1.1. Категории данных, не отмеченные как разрешённые, распространению не подлежат. Молчание не означает согласия: по части 8 статьи 10.1 Федерального закона № 152-ФЗ запреты и условия, установленные субъектом, обязательны для оператора.</p>");

    h.push("<h3>2. Где распространяется</h3>");
    h.push("<p>2.1. Разрешаю распространение перечисленных данных " + esc(pl.join("; ")) + ".</p>");
    h.push("<p>2.2. Иные информационные ресурсы, а также передача данных третьим лицам настоящим согласием не разрешены.</p>");

    h.push("<h3>3. Условия и запреты</h3>");
    h.push("<p>3.1. Запрещается использование данных и изображения Ребёнка в целях, не указанных в основном согласии, а также способами, порочащими его честь и достоинство или способными причинить вред его интересам.</p>");
    h.push("<p>3.2. Запрещается передача данных Ребёнка третьим лицам, их распространение в сети «Интернет» за пределами ресурсов, перечисленных в пункте 2.1, и предоставление доступа к ним неограниченному кругу лиц иными способами.</p>");
    h.push("<p>3.3. Настоящее согласие действует " + termText() + ".</p>");

    h.push("<h3>4. Отзыв согласия</h3>");
    h.push("<p>4.1. Согласие может быть отозвано в любое время письменным заявлением на имя Оператора. С момента получения заявления Оператор обязан прекратить передачу (распространение, предоставление, доступ) персональных данных (ч. 12 ст. 10.1 Федерального закона № 152-ФЗ).</p>");
    h.push("<p>4.2. Требование об удалении уже распространённых данных может быть направлено Оператору отдельно; при отказе или отсутствии ответа законный представитель вправе обратиться в суд.</p>");

    h.push('<table class="req"><tr><td><b>Законный представитель</b>' + bl(val("f-parent")) +
      "<br>за несовершеннолетнего " + bl(val("f-child")) +
      '<div class="sig">Подпись: ' + BL + "</div></td>" +
      "<td><b>Оператор</b>" + bl(val("f-org")) +
      '<div class="sig">Подпись: ' + BL + "</div></td></tr></table>");
    h.push('<p class="doc-note">Типовой шаблон собран конструктором pobubnim.ru по ст. 10.1 Федерального закона № 152-ФЗ. Не является юридической консультацией.</p>');
    h.push('<div class="bmark-row br" aria-hidden="true"><span class="bmark">Б</span></div>');
    paper.innerHTML = h.join("");
  }

  function render() {
    /* поля, зависящие от выбора */
    document.getElementById("wrap-years").hidden = radio("term") !== "years";
    document.getElementById("wrap-addr").hidden = radio("who") === "person";
    var pl = places();
    /* вкладка второго листа подсвечивается только когда он нужен */
    tab2.classList.toggle("need", pl.length > 0);
    document.getElementById("hint-rasp").hidden = pl.length === 0;
    document.getElementById("hint-norasp").hidden = pl.length > 0;

    if (mode === "osn") renderOsn(); else renderRasp();
  }

  function setMode(m) {
    mode = m;
    tab1.classList.toggle("on", m === "osn");
    tab2.classList.toggle("on", m === "rasp");
    tab1.setAttribute("aria-selected", m === "osn" ? "true" : "false");
    tab2.setAttribute("aria-selected", m === "rasp" ? "true" : "false");
    render();
  }
  tab1.addEventListener("click", function () { setMode("osn"); });
  tab2.addEventListener("click", function () { setMode("rasp"); });

  form.addEventListener("input", render);
  form.addEventListener("change", render);

  document.getElementById("btn-copy").addEventListener("click", function () {
    var btn = this, txt = paper.innerText;
    function done() {
      var old = btn.textContent;
      btn.textContent = "Скопировано ✓";
      btn.classList.add("copy-done");
      setTimeout(function () { btn.textContent = old; btn.classList.remove("copy-done"); }, 1600);
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(txt).then(done);
    } else {
      var ta = document.createElement("textarea");
      ta.value = txt; document.body.appendChild(ta); ta.select();
      document.execCommand("copy"); document.body.removeChild(ta); done();
    }
  });
  document.getElementById("btn-doc").addEventListener("click", function () {
    PobubnimDocx.download(paper, (mode === "osn" ? "soglasie-na-semku-rebenka" : "soglasie-na-rasprostranenie") + "-pobubnim.docx");
  });
  document.getElementById("btn-print").addEventListener("click", function () { window.print(); });

  /* окно для приёмки: тест смотрит то же состояние, что и страница */
  window.PobubnimReb = {
    places: places,
    mode: function () { return mode; },
    setMode: setMode
  };

  render();
})();
