TITLE = re.compile(r"<title>(.*?)</title>", re.S)
DESC = re.compile(r'(<meta name="description" content=")(.*?)(">)', re.S)
OG = re.compile(r'(<meta property="og:title" content=")(.*?)(">)', re.S)
H1 = re.compile(r'(<h1[^>]*>\s*<span class="label"[^>]*>)(.*?)(</span>)', re.S)


def main() -> int:
    check, bad = "--check" in sys.argv, 0
    for rel, (title, desc, h1) in HEAD.items():
        full = title + BRAND
        if not 50 <= len(full) <= 65:
            print(f"ВНЕ ВИЛКИ title {len(full)}: {rel}")
            bad += 1
        if not 150 <= len(desc) <= 190:
            print(f"ВНЕ ВИЛКИ description {len(desc)}: {rel}")
            bad += 1
        path = os.path.join(ROOT, rel)
        src = io.open(path, encoding="utf-8").read()
        new = TITLE.sub("<title>" + full + "</title>", src, count=1)
        new = DESC.sub(lambda m: m.group(1) + desc + m.group(3), new, count=1)
        new = OG.sub(lambda m: m.group(1) + full + m.group(3), new, count=1)
        new, n = H1.subn(lambda m: m.group(1) + h1 + m.group(3), new, count=1)
        if n != 1:
            print("нет запросной строки в H1:", rel)
            bad += 1
        if new != src:
            if check:
                print("расходится с таблицей:", rel)
                bad += 1
            else:
                io.open(path, "w", encoding="utf-8", newline="\n").write(new)
                print("обновлено:", rel)
    print("страниц в таблице:", len(HEAD), "· замечаний:", bad)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
